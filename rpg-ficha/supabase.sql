-- =====================================================================
-- Ficha RPG / Grimório — esquema para Supabase (PostgreSQL)
-- Como usar: Supabase > SQL Editor > New query > cole tudo > Run
-- Este arquivo é seguro de rodar mais de uma vez: ele só cria o que
-- ainda não existe e atualiza políticas/funções para a versão atual.
-- Cada usuário logado só enxerga as PRÓPRIAS fichas (Row Level Security).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) TABELAS
-- ---------------------------------------------------------------------

-- Personagem (aba Ficha). Um usuário pode ter várias fichas.
create table if not exists public.characters (
  id          uuid primary key default gen_random_uuid(),
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name        text not null,
  player      text,
  race        text,
  klass       text,                          -- classe ("class" é palavra reservada)
  level       int  not null default 1,
  age         int,
  height      numeric(4,2),                  -- metros, ex.: 1.70
  weight      numeric(6,2),                  -- kg, ex.: 66
  elements    text[] not null default '{}',  -- ex.: {Fogo,Luz}
  hp          int  not null default 0,       -- vida atual
  hp_max      int  not null default 0,
  san         int  not null default 0,       -- sanidade atual
  san_max     int  not null default 0,
  image_url   text,                          -- foto do personagem (Storage)
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
-- Paleta de elementos do personagem (nome, ícone, cor) — editável no site,
-- por isso fica num jsonb em vez de uma lista fixa no código
alter table public.characters add column if not exists elements_meta jsonb not null default '[]'::jsonb;

-- Atributos e recursos (aba Status). Uma linha por item, então novos
-- status entram sem alterar a tabela: basta inserir outra linha.
create table if not exists public.stats (
  id            uuid primary key default gen_random_uuid(),
  character_id  uuid not null references public.characters(id) on delete cascade,
  kind          text not null check (kind in ('atributo', 'recurso')),
  name          text not null,               -- Força, Mana, Pontos de Ação...
  value         int  not null default 0,
  unique (character_id, kind, name)
);
-- Garante a coluna mesmo em bancos onde a tabela já existia sem ela
alter table public.stats add column if not exists sort bigint generated by default as identity;

-- Magias (aba Magias)
create table if not exists public.magics (
  id            uuid primary key default gen_random_uuid(),
  character_id  uuid not null references public.characters(id) on delete cascade,
  name          text not null,
  type          text,
  element       text,                        -- Fogo, Luz, Escuridão, Sangue, Selo, Bardo
  description   text,
  range         text,
  duration      text,
  effects       text,
  penalty       text,
  cooldown      text,
  created_at    timestamptz not null default now()
);

-- Passivas (aba Passivas)
create table if not exists public.passives (
  id            uuid primary key default gen_random_uuid(),
  character_id  uuid not null references public.characters(id) on delete cascade,
  name          text not null,
  category      text,
  description   text,
  active        boolean not null default false,  -- true = Ativa, false = Passiva
  notes         text,
  created_at    timestamptz not null default now()
);

-- Acessórios (aba Acessórios)
create table if not exists public.accessories (
  id            uuid primary key default gen_random_uuid(),
  character_id  uuid not null references public.characters(id) on delete cascade,
  name          text not null,
  type          text,
  description   text,
  bonus         text,
  resistances   text,                        -- uma por linha, ex.: "Frio +50%"
  image_url     text,                        -- imagem (Storage)
  created_at    timestamptz not null default now()
);

-- Índices nas chaves estrangeiras (deixam as consultas por ficha rápidas)
create index if not exists characters_user_id_idx  on public.characters  (user_id);
create index if not exists stats_character_id_idx  on public.stats       (character_id);
create index if not exists magics_character_id_idx on public.magics      (character_id);
create index if not exists passives_character_id_idx on public.passives  (character_id);
create index if not exists accessories_character_id_idx on public.accessories (character_id);

-- ---------------------------------------------------------------------
-- 2) updated_at automático na tabela characters
-- ---------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace trigger characters_set_updated_at
  before update on public.characters
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 3) SEGURANÇA (Row Level Security)
-- ---------------------------------------------------------------------

-- Diz se a ficha pertence ao usuário logado (usada nas tabelas filhas)
create or replace function public.owns_character(cid uuid)
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.characters
    where id = cid and user_id = (select auth.uid())
  );
$$;
grant execute on function public.owns_character(uuid) to authenticated;

alter table public.characters  enable row level security;
alter table public.stats       enable row level security;
alter table public.magics      enable row level security;
alter table public.passives    enable row level security;
alter table public.accessories enable row level security;

drop policy if exists "dono gerencia suas fichas" on public.characters;
create policy "dono gerencia suas fichas" on public.characters
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

drop policy if exists "dono gerencia seus status" on public.stats;
create policy "dono gerencia seus status" on public.stats
  for all to authenticated
  using (public.owns_character(character_id))
  with check (public.owns_character(character_id));

drop policy if exists "dono gerencia suas magias" on public.magics;
create policy "dono gerencia suas magias" on public.magics
  for all to authenticated
  using (public.owns_character(character_id))
  with check (public.owns_character(character_id));

drop policy if exists "dono gerencia suas passivas" on public.passives;
create policy "dono gerencia suas passivas" on public.passives
  for all to authenticated
  using (public.owns_character(character_id))
  with check (public.owns_character(character_id));

drop policy if exists "dono gerencia seus acessorios" on public.accessories;
create policy "dono gerencia seus acessorios" on public.accessories
  for all to authenticated
  using (public.owns_character(character_id))
  with check (public.owns_character(character_id));

-- Permissões de acesso às tabelas (o RLS acima filtra as linhas)
grant select, insert, update, delete on
  public.characters, public.stats, public.magics, public.passives, public.accessories
  to authenticated;

-- ---------------------------------------------------------------------
-- 4) STORAGE para imagens (personagem e acessórios)
--    Bucket público para leitura; só o dono grava na pasta com o seu id:
--    caminho do arquivo = <user_id>/<nome-do-arquivo>
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('character-images', 'character-images', true)
on conflict (id) do nothing;

drop policy if exists "upload na propria pasta" on storage.objects;
create policy "upload na propria pasta" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'character-images'
              and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "atualiza na propria pasta" on storage.objects;
create policy "atualiza na propria pasta" on storage.objects
  for update to authenticated
  using (bucket_id = 'character-images'
         and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "apaga na propria pasta" on storage.objects;
create policy "apaga na propria pasta" on storage.objects
  for delete to authenticated
  using (bucket_id = 'character-images'
         and (storage.foldername(name))[1] = (select auth.uid())::text);

-- ---------------------------------------------------------------------
-- 5) FICHA INICIAL (Elisa) — chame pelo app depois do login:
--      supabase.rpc('seed_elisa')
--    Não rode pelo SQL Editor: lá não existe usuário logado (auth.uid() é nulo).
-- ---------------------------------------------------------------------
create or replace function public.seed_elisa()
returns uuid
language plpgsql
as $$
declare
  cid uuid;
begin
  insert into public.characters
    (name, player, race, klass, level, age, height, weight, elements, hp, hp_max, san, san_max)
  values
    ('Elisa', 'Ronan', 'Nokturno', 'Ilusionista Materializadora / Bardo', 12, 1309, 1.70, 66,
     array['Fogo', 'Luz', 'Escuridão', 'Sangue', 'Selo'], 403, 403, 100, 100)
  returning id into cid;

  insert into public.stats (character_id, kind, name, value) values
    (cid, 'atributo', 'Força',          339),
    (cid, 'atributo', 'Velocidade',     363),
    (cid, 'atributo', 'Defesa',         402),
    (cid, 'atributo', 'Inteligência',   202),
    (cid, 'atributo', 'Sabedoria',      156),
    (cid, 'atributo', 'Carisma',        104),
    (cid, 'recurso',  'Pontos de Ação', 0),
    (cid, 'recurso',  'Mana',           0),
    (cid, 'recurso',  'Energia',        0);

  return cid;
end;
$$;
grant execute on function public.seed_elisa() to authenticated;
